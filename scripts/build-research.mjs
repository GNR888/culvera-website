#!/usr/bin/env node
/**
 * Culvera AI — Research & Insights page generator
 * ----------------------------------------------------------------------
 * Builds static, crawlable HTML from content/research-insights/:
 *
 *   research-insights/index.html          article library (newest first)
 *   research-insights/<slug>/index.html   one page per article
 *   sitemap.xml                           only when content/site.mjs has a url
 *
 * The output is committed like any other page, so hosting still needs no
 * build step: run this after adding or editing an article, then commit.
 *
 *   node scripts/build-research.mjs
 *
 * Zero dependencies (Node 18+). Every generated file starts with a
 * "generated" banner. Edit the content files, never the output.
 */
import { readFile, writeFile, mkdir, rm, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

import { site } from "../content/site.mjs";
import { articles as rawArticles, TOPICS } from "../content/research-insights/articles.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT_DIR = path.join(ROOT, "content", "research-insights");
const OUT_DIR = path.join(ROOT, "research-insights");
const SECTION_PATH = "research-insights/";
const SECTION_NAME = "Research & Insights";
const WORDS_PER_MINUTE = 220;
const RELATED_COUNT = 3;

const BANNER = `<!-- GENERATED by scripts/build-research.mjs from content/research-insights/.
     Do not edit this file by hand; edit the content and re-run the script. -->`;

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Root-relative or absolute (when site.url is set) URL for a site path. */
function publicUrl(sitePath) {
  const base = site.url ? site.url.replace(/\/+$/, "") : "";
  return `${base}/${sitePath}`;
}

function formatDate(isoDate) {
  return new Intl.DateTimeFormat("en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${isoDate}T00:00:00Z`));
}

function estimateReadingTime(html) {
  const words = html.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / WORDS_PER_MINUTE));
}

function topicSlug(topic) {
  return topic
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** JSON for a <script type="application/ld+json"> block, safe to inline. */
function jsonLd(data) {
  return JSON.stringify(data, null, 2).replace(/</g, "\\u003c");
}

// ---------------------------------------------------------------------------
// Load + validate content
// ---------------------------------------------------------------------------

const REQUIRED_FIELDS = ["slug", "title", "description", "excerpt", "topics", "date", "image", "imageAlt"];

async function loadArticles() {
  const slugs = new Set();

  for (const article of rawArticles) {
    for (const field of REQUIRED_FIELDS) {
      if (!article[field] || (Array.isArray(article[field]) && article[field].length === 0)) {
        throw new Error(`Article "${article.slug ?? article.title}" is missing "${field}".`);
      }
    }
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(article.slug)) {
      throw new Error(`Slug "${article.slug}" must be lowercase words separated by hyphens.`);
    }
    if (slugs.has(article.slug)) throw new Error(`Duplicate slug "${article.slug}".`);
    slugs.add(article.slug);
    for (const topic of article.topics) {
      if (!TOPICS.includes(topic)) {
        throw new Error(`Article "${article.slug}" uses unknown topic "${topic}". Add it to TOPICS first.`);
      }
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(article.date)) {
      throw new Error(`Article "${article.slug}" date must be YYYY-MM-DD.`);
    }
  }

  const loaded = await Promise.all(
    rawArticles.map(async (article) => {
      const bodyPath = path.join(CONTENT_DIR, `${article.slug}.html`);
      const body = await readFile(bodyPath, "utf8").catch(() => {
        throw new Error(`Missing body file for "${article.slug}": ${path.relative(ROOT, bodyPath)}`);
      });
      if (/<h1[\s>]/i.test(body)) {
        throw new Error(`${article.slug}.html must not contain an <h1>; the page title is the only one.`);
      }
      for (const [, target] of body.matchAll(/\{\{article:([^}]+)\}\}/g)) {
        if (!slugs.has(target)) {
          throw new Error(`${article.slug}.html links to unknown article "${target}".`);
        }
      }
      return {
        ...article,
        category: article.topics[0],
        sources: article.sources ?? [],
        body,
        readingTime: article.readingTime ?? estimateReadingTime(body),
      };
    })
  );

  // Newest first; ties broken by title so output is stable.
  return loaded.sort((a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title));
}

/**
 * Up to RELATED_COUNT other articles, ranked by shared topics (a shared
 * primary category counts extra), then recency. Falls back to the newest
 * remaining articles so the section is never empty while others exist.
 */
function relatedArticles(article, all) {
  return all
    .filter((other) => other.slug !== article.slug)
    .map((other) => {
      const shared = other.topics.filter((topic) => article.topics.includes(topic)).length;
      const sameCategory = other.category === article.category ? 2 : 0;
      return { other, score: shared + sameCategory };
    })
    .sort((a, b) => b.score - a.score || b.other.date.localeCompare(a.other.date))
    .slice(0, RELATED_COUNT)
    .map(({ other }) => other);
}

// ---------------------------------------------------------------------------
// Shared page chrome (mirrors the static-header pages, e.g. contact.html)
// ---------------------------------------------------------------------------

function renderHead({ root, title, description, canonicalPath, ogType, image, imageAlt, structuredData }) {
  const canonical = publicUrl(canonicalPath);
  const socialTags = [
    `<meta property="og:site_name" content="${escapeHtml(site.name)}" />`,
    `<meta property="og:type" content="${ogType}" />`,
    `<meta property="og:title" content="${escapeHtml(title)}" />`,
    `<meta property="og:description" content="${escapeHtml(description)}" />`,
    `<meta name="twitter:card" content="${image ? "summary_large_image" : "summary"}" />`,
  ];
  // Open Graph URLs must be absolute, so these only appear once site.url is set.
  if (site.url) {
    socialTags.push(`<meta property="og:url" content="${escapeHtml(canonical)}" />`);
    if (image) {
      socialTags.push(`<meta property="og:image" content="${escapeHtml(publicUrl(image))}" />`);
      socialTags.push(`<meta property="og:image:alt" content="${escapeHtml(imageAlt)}" />`);
    }
  }

  return `<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${escapeHtml(title)}</title>
  <meta
    name="description"
    content="${escapeHtml(description)}"
  />
  <link rel="canonical" href="${escapeHtml(canonical)}" />

  ${socialTags.join("\n  ")}

  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link
    href="https://fonts.googleapis.com/css2?family=Montserrat:wght@300;400;500&family=Inter:wght@400;500;600&display=swap"
    rel="stylesheet"
  />

  <link rel="stylesheet" href="${root}css/variables.css" />
  <link rel="stylesheet" href="${root}css/base.css" />
  <link rel="stylesheet" href="${root}css/hero.css" />
  <link rel="stylesheet" href="${root}css/footer.css" />
  <link rel="stylesheet" href="${root}css/contact.css" />
  <link rel="stylesheet" href="${root}css/about-sections.css" />
  <link rel="stylesheet" href="${root}css/editorial.css" />
${structuredData ? `\n  <script type="application/ld+json">\n${jsonLd(structuredData)}\n  </script>\n` : ""}</head>`;
}

function renderHeader(root) {
  return `<header class="site-header site-header--static">
    <a class="site-header__brand" href="${root}index.html">
      <img
        class="site-header__logo"
        src="${root}assets/images/logo-gold.png"
        alt=""
      />
      <span class="site-header__wordmark">CULVERA AI</span>
    </a>
    <nav class="site-header__nav" aria-label="Primary">
      <a href="${root}demo.html">DEMO</a>
      <a href="${root}about.html">ABOUT</a>
      <a href="${root}contact.html">CONTACT</a>
    </nav>
  </header>`;
}

function renderPage({ head, root, main, scripts = [] }) {
  const moduleScripts = [...scripts, "js/footer.js", "js/scroll-reveal.js"]
    .map((src) => `  <script type="module" src="${root}${src}"></script>`)
    .join("\n");

  return `<!DOCTYPE html>
${BANNER}
<html lang="en">
${head}
<body class="contact-page">

  ${renderHeader(root)}

  <main>
${main}
  </main>

  <footer id="site-footer"></footer>

${moduleScripts}
</body>
</html>
`;
}

