function renderSources(sources) {
  if (sources.length === 0) return "";
  return `
        <section class="article-sources" aria-labelledby="sources-heading">
          <h2 class="article-sources__heading" id="sources-heading">Sources</h2>
          <ol class="article-sources__list">
            ${sources
              .map(
                (source, index) => `<li id="source-${index + 1}">
              ${escapeHtml(source.publisher)}, <a href="${escapeHtml(source.url)}" target="_blank" rel="noopener">${escapeHtml(source.title)}</a>
            </li>`
              )
              .join("\n            ")}
          </ol>
        </section>`;
}

function renderArticle(article, all) {
  const root = "../../";
  const pagePath = `${SECTION_PATH}${article.slug}/`;
  const body = article.body
    .replace(/\{\{root\}\}/g, root)
    .replace(/\{\{article:([^}]+)\}\}/g, (_, slug) => `../${slug}/`)
    .trim();
  const related = relatedArticles(article, all);
  const updated = article.updated && article.updated !== article.date ? article.updated : null;

  const main = `    <article class="article">
      <header class="article-header">
        <p class="article-header__crumbs">
          <a href="../">${SECTION_NAME}</a>
          <span aria-hidden="true">/</span>
          <span>${escapeHtml(article.category)}</span>
        </p>
        <h1 class="article-header__title">${escapeHtml(article.title)}</h1>
        <p class="article-header__dek">${escapeHtml(article.excerpt)}</p>
        <p class="article-header__meta">
          <span>By ${escapeHtml(site.name)}</span>
          <span aria-hidden="true">&middot;</span>
          <time datetime="${article.date}">${formatDate(article.date)}</time>
          <span aria-hidden="true">&middot;</span>
          <span>${article.readingTime} min read</span>${
            updated
              ? `
          <span aria-hidden="true">&middot;</span>
          <span>Updated <time datetime="${updated}">${formatDate(updated)}</time></span>`
              : ""
          }
        </p>
      </header>

      <figure class="article-figure">
        <img src="${root}${article.image}" alt="${escapeHtml(article.imageAlt)}" fetchpriority="high" decoding="async" />
      </figure>

      <div class="article-layout">
        <div class="prose article-body">
${body}
        </div>
${renderSources(article.sources)}

        <aside class="article-about" aria-label="About Culvera">
          <p>
            Culvera AI is building agricultural decision intelligence, starting with smallholder
            farming in Vietnam. Learn <a href="${root}about.html">why we started in Vietnam</a>,
            see <a href="${root}demo.html">how the platform works</a>, or
            <a href="${root}contact.html">get in touch about research partnerships</a>.
          </p>
        </aside>
      </div>
    </article>
${
  related.length
    ? `
    <section class="contact-section related-insights" aria-labelledby="related-heading">
      <div class="related-insights__header">
        <h2 class="related-insights__heading" id="related-heading">Related research</h2>
        <a class="related-insights__all" href="../">All articles &rarr;</a>
      </div>
      <div class="insights-grid insights-grid--related" data-reveal-group>${related.map((a) => renderCard(a, root, "h3")).join("")}
      </div>
    </section>`
    : ""
}`;

  const head = renderHead({
    root,
    title: `${article.seoTitle ?? article.title} | ${site.name}`,
    description: article.description,
    canonicalPath: pagePath,
    ogType: "article",
    image: article.image,
    imageAlt: article.imageAlt,
    structuredData: {
      "@context": "https://schema.org",
      "@type": "Article",
      headline: article.title,
      description: article.description,
      datePublished: article.date,
      dateModified: updated ?? article.date,
      articleSection: article.category,
      keywords: article.topics.join(", "),
      ...(site.url && {
        image: [publicUrl(article.image)],
        mainEntityOfPage: publicUrl(pagePath),
      }),
      author: { "@type": "Organization", name: site.name, ...(site.url && { url: publicUrl("") }) },
      publisher: {
        "@type": "Organization",
        name: site.name,
        ...(site.url && {
          url: publicUrl(""),
          logo: { "@type": "ImageObject", url: publicUrl("assets/images/logo-gold.png") },
        }),
      },
      ...(article.sources.length && { citation: article.sources.map((s) => s.url) }),
    },
  });

  return renderPage({ head, root, main });
}

// ---------------------------------------------------------------------------
// Sitemap (absolute URLs required, so only when site.url is configured)
// ---------------------------------------------------------------------------

async function renderSitemap(articles) {
  const topLevelPages = (await readdir(ROOT))
    .filter((file) => file.endsWith(".html"))
    .sort()
    .map((file) => (file === "index.html" ? "" : file));

  const entries = [
    ...topLevelPages.map((p) => ({ loc: publicUrl(p) })),
    { loc: publicUrl(SECTION_PATH), lastmod: articles[0]?.date },
    ...articles.map((a) => ({ loc: publicUrl(`${SECTION_PATH}${a.slug}/`), lastmod: a.updated ?? a.date })),
  ];

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/build-research.mjs. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries
  .map((e) => `  <url><loc>${escapeHtml(e.loc)}</loc>${e.lastmod ? `<lastmod>${e.lastmod}</lastmod>` : ""}</url>`)
  .join("\n")}
</urlset>
`;
}

// ---------------------------------------------------------------------------
// Build
// ---------------------------------------------------------------------------

async function build() {
  const articles = await loadArticles();

  // Start clean so deleted/renamed articles don't leave stale pages behind.
  await rm(OUT_DIR, { recursive: true, force: true });
  await mkdir(OUT_DIR, { recursive: true });

  await writeFile(path.join(OUT_DIR, "index.html"), renderIndex(articles));
  for (const article of articles) {
    const dir = path.join(OUT_DIR, article.slug);
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(dir, "index.html"), renderArticle(article, articles));
  }

  const sitemapPath = path.join(ROOT, "sitemap.xml");
  if (site.url) {
    await writeFile(sitemapPath, await renderSitemap(articles));
  } else {
    await rm(sitemapPath, { force: true });
  }

  console.log(`Built ${SECTION_NAME}: index + ${articles.length} article page(s).`);
  for (const a of articles) console.log(`  /${SECTION_PATH}${a.slug}/  (${a.date}, ${a.readingTime} min)`);
  if (!site.url) console.log("Note: content/site.mjs has no url, so canonical links are root-relative and sitemap.xml was skipped.");
}

build().catch((error) => {
  console.error(`Build failed: ${error.message}`);
  process.exit(1);
});
