/**
 * @param {object} article
 * @param {string} root       path from the current page to the site root
 * @param {string} headingTag heading element for the title (keeps outline valid)
 */
function renderCard(article, root, headingTag) {
  const href = `${root}${SECTION_PATH}${article.slug}/`;
  const topics = article.topics.map(topicSlug).join(" ");

  return `
        <article class="insight-card" data-topics="${topics}">
          <div class="insight-card__media">
            <img src="${root}${article.image}" alt="${escapeHtml(article.imageAlt)}" loading="lazy" decoding="async" />
          </div>
          <div class="insight-card__body">
            <p class="insight-card__category">${escapeHtml(article.category)}</p>
            <${headingTag} class="insight-card__title">
              <a class="insight-card__link" href="${href}">${escapeHtml(article.title)}</a>
            </${headingTag}>
            <p class="insight-card__excerpt">${escapeHtml(article.excerpt)}</p>
            <p class="insight-card__meta">
              <time datetime="${article.date}">${formatDate(article.date)}</time>
              <span aria-hidden="true">&middot;</span>
              <span>${article.readingTime} min read</span>
            </p>
            <span class="insight-card__cta" aria-hidden="true">Read article &rarr;</span>
          </div>
        </article>`;
}

// ---------------------------------------------------------------------------
// Index page
// ---------------------------------------------------------------------------

function renderIndex(articles) {
  const root = "../";
  const usedTopics = TOPICS.filter((topic) => articles.some((a) => a.topics.includes(topic)));
  const filters =
    usedTopics.length > 1
      ? `
      <div class="insights-filters" data-insights-filters role="group" aria-label="Filter articles by topic" hidden>
        <button type="button" class="insights-filter" data-topic="all" aria-pressed="true">All</button>
        ${usedTopics
          .map(
            (topic) =>
              `<button type="button" class="insights-filter" data-topic="${topicSlug(topic)}" aria-pressed="false">${escapeHtml(topic)}</button>`
          )
          .join("\n        ")}
      </div>`
      : "";

  const title = `${SECTION_NAME} | ${site.name}`;
  const description =
    "Research-based articles from Culvera AI on agriculture, climate resilience, rice and methane, smallholder farming, remote sensing and agricultural decision intelligence in Vietnam and Southeast Asia.";

  const main = `    <section class="contact-hero contact-section insights-hero">
      <div class="contact-hero__inner contact-hero__inner--wide">
        <p class="contact-hero__eyebrow">CULVERA RESEARCH LIBRARY</p>
        <h1 class="contact-hero__title">Research &amp; Insights</h1>
        <p class="contact-hero__body">
          Culvera publishes research-based articles on the questions behind our work:
          agriculture and climate resilience in Vietnam and Southeast Asia, smallholder
          farming, rice production and methane emissions, soil and water management, and
          how weather, satellite and remote sensing data can become practical agricultural
          decision intelligence.
        </p>
      </div>
    </section>

    <section class="contact-section insights" aria-labelledby="insights-heading">
      <h2 class="visually-hidden" id="insights-heading">Latest articles</h2>
${filters}
      <div class="insights-grid" data-insights-grid data-reveal-group>${articles.map((a) => renderCard(a, root, "h3")).join("")}
      </div>
      <p class="insights-empty" data-insights-empty hidden>No articles on this topic yet.</p>
    </section>`;

  const head = renderHead({
    root,
    title,
    description,
    canonicalPath: SECTION_PATH,
    ogType: "website",
    structuredData: {
      "@context": "https://schema.org",
      "@type": "CollectionPage",
      name: SECTION_NAME,
      description,
      ...(site.url && { url: publicUrl(SECTION_PATH) }),
      hasPart: articles.map((a) => ({
        "@type": "Article",
        headline: a.title,
        datePublished: a.date,
        ...(site.url && { url: publicUrl(`${SECTION_PATH}${a.slug}/`) }),
      })),
    },
  });

  return renderPage({ head, root, main, scripts: ["js/research-filters.js"] });
}

// ---------------------------------------------------------------------------
// Article page
